// Regenerates src/data/world-dots.ts, the land mask behind the live connections map.
//
//   node scripts/world-dots.mjs
//
// Downloads world-atlas@2.0.2 (ISC; Natural Earth 1:110m land, public domain) with `npm pack`,
// decodes the TopoJSON, and marks which cells of a 2-degree equirectangular grid fall on land.
// The output is a base64 bitset of about 2 KB, so the page ships no map tiles, no TopoJSON and
// no map library, and fetches nothing at runtime. Only needed when changing the grid.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const STEP = 2;
const NORTH = 84;
const SOUTH = -58;
const COLS = 360 / STEP;
const ROWS = (NORTH - SOUTH) / STEP;

const work = mkdtempSync(join(tmpdir(), "world-atlas-"));
try {
  execFileSync("npm", ["pack", "world-atlas@2.0.2", "--pack-destination", work, "--silent"], { stdio: "inherit" });
  execFileSync("tar", ["-xzf", join(work, "world-atlas-2.0.2.tgz"), "-C", work]);
  const topology = JSON.parse(readFileSync(join(work, "package", "land-110m.json"), "utf8"));

  const { scale, translate } = topology.transform;
  const arcs = topology.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
    });
  });
  const ring = (indexes) => {
    const points = [];
    for (const index of indexes) {
      const arc = index < 0 ? arcs[~index].slice().reverse() : arcs[index];
      points.push(...(points.length ? arc.slice(1) : arc));
    }
    return points;
  };
  const rings = [];
  for (const geometry of topology.objects.land.geometries) {
    const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
    for (const polygon of polygons) for (const indexes of polygon) rings.push(ring(indexes));
  }

  // Even-odd over every ring, so lakes and inland seas that are holes stay water.
  const onLand = (lon, lat) => {
    let inside = false;
    for (const points of rings) {
      for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
        const [xi, yi] = points[i];
        const [xj, yj] = points[j];
        if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
      }
    }
    return inside;
  };

  const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
  let land = 0;
  for (let row = 0; row < ROWS; row++) {
    for (let col = 0; col < COLS; col++) {
      if (onLand(-180 + STEP * col + STEP / 2, NORTH - STEP * row - STEP / 2)) {
        const n = row * COLS + col;
        bits[n >> 3] |= 1 << (n & 7);
        land++;
      }
    }
  }

  const out = fileURLToPath(new URL("../src/data/world-dots.ts", import.meta.url));
  writeFileSync(
    out,
    `// Generated by scripts/world-dots.mjs from world-atlas@2.0.2 land-110m (ISC; Natural Earth, public domain).
// A ${COLS}x${ROWS} grid of ${STEP}-degree cells from ${NORTH}N to ${SOUTH}S; bit row*cols+col is set when the cell is land.
export const WORLD_DOTS = {
  step: ${STEP},
  north: ${NORTH},
  cols: ${COLS},
  rows: ${ROWS},
  bits: "${Buffer.from(bits).toString("base64")}",
} as const;
`,
  );
  console.log(`wrote ${out}: ${land} land cells of ${COLS * ROWS}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
